CREATE TABLE reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    veiculo_id BIGINT NOT NULL,
    data_retirada DATE NOT NULL,
    data_devolucao DATE NOT NULL,
    valor_diaria NUMERIC(10, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reservas_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES clientes (id),

    CONSTRAINT fk_reservas_veiculo
        FOREIGN KEY (veiculo_id)
        REFERENCES veiculos (id),

    CONSTRAINT ck_reservas_status
        CHECK (
            status IN (
                'PENDENTE',
                'CONFIRMADA'
                'CANCELADA',
                'CONCLUIDA'
                )
            )
);

CREATE INDEX idx_reservas_cliente_id
    ON reservas (cliente_id);

CREATE INDEX idx_reservas_veiculo_periodo
    ON reservas (veiculo_id, data_retirada, data_devolucao);