-- Tabela de categorias de veiculos
CREATE TABLE categorias_veiculos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(255),
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);

-- Tabela de veiculos
CREATE TABLE veiculos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL,
    marca VARCHAR(100) NOT NULL,
    modelo VARCHAR(100) NOT NULL,
    ano_fabricacao INTEGER NOT NULL,
    placa VARCHAR(10) NOT NULL UNIQUE,
    cor VARCHAR(50),
    quilometragem INTEGER NOT NULL DEFAULT 0,
    valor_diaria NUMERIC(10,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DISPONIVEL',

    CONSTRAINT fk_veiculos_ano CHECK (ano_fabricacao >= 1900),

    CONSTRAINT ck_veiculos_quilometragem CHECK (quilometragem >= 0),

    CONSTRAINT ck_veiculos_valor_diaria CHECK (valor_diaria > 0),

    CONSTRAINT ck_veiculos_status CHECK (status IN ('DISPONIVEL', 'RESERVADO', 'ALUGADO', 'MANUTENCAO', 'INATIVO'))
);

-- indice para consultas de veiculos por categoria
CREATE INDEX  idx_veiculos_categoria_id ON veiculos (categoria_id);